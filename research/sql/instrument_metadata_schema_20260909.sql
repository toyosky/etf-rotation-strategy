-- Instrument metadata / asset-exposure taxonomy for ETF + LOF universe.
-- Applied first to Supabase project ETF_daily_bars on 2026-09-09.

create table if not exists public.instrument_metadata (
  id bigint generated by default as identity primary key,
  symbol text not null,
  name text,
  product_type text not null default 'UNKNOWN',
  asset_class text not null default 'OTHER',
  region_primary text,
  region_tags text[] not null default '{}',
  exposure_level1 text,
  exposure_level2 text,
  underlying_key text,
  risk_bucket text,
  style_sector text,
  is_qdii boolean,
  nav_lag_days smallint,
  premium_sensitive boolean not null default false,
  t0_flag boolean,
  derivative_exposure boolean not null default false,
  roll_cost_exposure boolean not null default false,
  currency_exposure text,
  leveraged_flag boolean not null default false,
  inverse_flag boolean not null default false,
  data_start_date date,
  data_end_date date,
  bars_count integer,
  label_scope text not null default 'CURRENT_SNAPSHOT',
  historical_safe boolean not null default false,
  valid_from date not null,
  valid_to date,
  classification_method text,
  confidence numeric(4,3),
  needs_review boolean not null default true,
  metadata_source text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint instrument_metadata_symbol_valid_from_key unique(symbol, valid_from),
  constraint instrument_metadata_validity_chk check(valid_to is null or valid_to >= valid_from),
  constraint instrument_metadata_confidence_chk check(confidence is null or (confidence >= 0 and confidence <= 1))
);

create index if not exists instrument_metadata_symbol_idx on public.instrument_metadata(symbol);
create index if not exists instrument_metadata_risk_bucket_idx on public.instrument_metadata(risk_bucket);
create index if not exists instrument_metadata_underlying_key_idx on public.instrument_metadata(underlying_key);
create index if not exists instrument_metadata_review_idx on public.instrument_metadata(needs_review) where needs_review;

alter table public.instrument_metadata enable row level security;

create or replace view public.instrument_metadata_current with (security_invoker = true) as
select distinct on (symbol) *
from public.instrument_metadata
where valid_to is null
order by symbol, valid_from desc, id desc;
